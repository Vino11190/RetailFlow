
-- ============================================================
-- RetailFlow: Phase 7 Gold Dimensional Warehouse
-- PostgreSQL 17
-- ============================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ============================================================
-- 1. DIMENSIONS
-- ============================================================

CREATE TABLE IF NOT EXISTS gold.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE UNIQUE,
    year INTEGER,
    quarter INTEGER,
    month INTEGER,
    month_name VARCHAR(20),
    day INTEGER,
    day_of_week INTEGER,
    day_name VARCHAR(20),
    is_weekend BOOLEAN
);

CREATE TABLE IF NOT EXISTS gold.dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(100) UNIQUE,
    city VARCHAR(150),
    postcode VARCHAR(30),
    country VARCHAR(100),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS gold.dim_product (
    product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id VARCHAR(100) NOT NULL,
    sku VARCHAR(100),
    product_name VARCHAR(255),
    category_id VARCHAR(100),
    category_name VARCHAR(150),
    brand VARCHAR(150),
    unit_price NUMERIC(18, 2),
    currency VARCHAR(10),
    active BOOLEAN,
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    attribute_hash CHAR(64) NOT NULL,
    CONSTRAINT ck_product_effective_dates
        CHECK (
            effective_to IS NULL
            OR effective_to > effective_from
        ),
    CONSTRAINT ck_product_current_period
        CHECK (
            (is_current AND effective_to IS NULL)
            OR
            (NOT is_current AND effective_to IS NOT NULL)
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_product_current
ON gold.dim_product (product_id)
WHERE is_current = TRUE;

-- Prevent overlapping historical periods for a product.
ALTER TABLE gold.dim_product
    ADD CONSTRAINT ex_dim_product_no_overlap
    EXCLUDE USING gist (
        product_id WITH =,
        tstzrange(
            effective_from,
            effective_to,
            '[)'
        ) WITH &&
    );

CREATE TABLE IF NOT EXISTS gold.dim_store (
    store_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id VARCHAR(100) UNIQUE
);

CREATE TABLE IF NOT EXISTS gold.dim_supplier (
    supplier_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id VARCHAR(100) UNIQUE,
    supplier_name VARCHAR(255),
    country VARCHAR(100),
    lead_time_days INTEGER,
    active BOOLEAN
);

CREATE TABLE IF NOT EXISTS gold.dim_channel (
    channel_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_name VARCHAR(100) UNIQUE
);

-- ============================================================
-- 2. FACT TABLES
-- ============================================================

CREATE TABLE IF NOT EXISTS gold.fact_ecommerce_sales (
    sales_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id VARCHAR(100) NOT NULL UNIQUE,
    order_id VARCHAR(100) NOT NULL,
    customer_key BIGINT NOT NULL
        REFERENCES gold.dim_customer(customer_key),
    product_key BIGINT NOT NULL
        REFERENCES gold.dim_product(product_key),
    date_key INTEGER NOT NULL
        REFERENCES gold.dim_date(date_key),
    channel_key BIGINT NOT NULL
        REFERENCES gold.dim_channel(channel_key),
    order_timestamp TIMESTAMPTZ,
    order_status VARCHAR(50),
    currency VARCHAR(10),
    quantity BIGINT,
    unit_price NUMERIC(18, 2),
    discount NUMERIC(18, 2),
    line_total NUMERIC(18, 2)
);

CREATE TABLE IF NOT EXISTS gold.fact_pos_sales (
    pos_sales_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL UNIQUE,
    product_key BIGINT NOT NULL
        REFERENCES gold.dim_product(product_key),
    store_key BIGINT NOT NULL
        REFERENCES gold.dim_store(store_key),
    date_key INTEGER NOT NULL
        REFERENCES gold.dim_date(date_key),
    channel_key BIGINT NOT NULL
        REFERENCES gold.dim_channel(channel_key),
    transaction_timestamp TIMESTAMPTZ,
    payment_method VARCHAR(100),
    quantity BIGINT,
    unit_price NUMERIC(18, 2),
    discount NUMERIC(18, 2),
    total_amount NUMERIC(18, 2)
);

CREATE TABLE IF NOT EXISTS gold.fact_payments (
    payment_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(100) NOT NULL UNIQUE,
    order_id VARCHAR(100),
    date_key INTEGER NOT NULL
        REFERENCES gold.dim_date(date_key),
    payment_timestamp TIMESTAMPTZ,
    amount NUMERIC(18, 2),
    currency VARCHAR(10),
    status VARCHAR(50),
    payment_method VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS gold.fact_returns (
    return_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id VARCHAR(100) NOT NULL UNIQUE,
    order_id VARCHAR(100),
    customer_key BIGINT NOT NULL
        REFERENCES gold.dim_customer(customer_key),
    product_key BIGINT NOT NULL
        REFERENCES gold.dim_product(product_key),
    date_key INTEGER NOT NULL
        REFERENCES gold.dim_date(date_key),
    quantity BIGINT,
    reason VARCHAR(255),
    refund_amount NUMERIC(18, 2)
);

CREATE TABLE IF NOT EXISTS gold.fact_inventory_snapshot (
    snapshot_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_timestamp TIMESTAMPTZ NOT NULL,
    snapshot_date_key INTEGER NOT NULL
        REFERENCES gold.dim_date(date_key),
    product_key BIGINT NOT NULL
        REFERENCES gold.dim_product(product_key),
    store_key BIGINT NOT NULL
        REFERENCES gold.dim_store(store_key),
    quantity_on_hand BIGINT,
    reorder_level BIGINT,
    UNIQUE (
        snapshot_timestamp,
        product_key,
        store_key
    )
);

CREATE TABLE IF NOT EXISTS gold.fact_inventory_movements (
    movement_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id VARCHAR(100) NOT NULL UNIQUE,
    product_key BIGINT NOT NULL
        REFERENCES gold.dim_product(product_key),
    store_key BIGINT NOT NULL
        REFERENCES gold.dim_store(store_key),
    date_key INTEGER NOT NULL
        REFERENCES gold.dim_date(date_key),
    movement_timestamp TIMESTAMPTZ,
    movement_type VARCHAR(100),
    quantity BIGINT
);

CREATE TABLE IF NOT EXISTS gold.fact_supplier_deliveries (
    delivery_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id VARCHAR(100) NOT NULL UNIQUE,
    supplier_key BIGINT NOT NULL
        REFERENCES gold.dim_supplier(supplier_key),
    product_key BIGINT NOT NULL
        REFERENCES gold.dim_product(product_key),
    expected_date_key INTEGER NOT NULL
        REFERENCES gold.dim_date(date_key),
    actual_date_key INTEGER
        REFERENCES gold.dim_date(date_key),
    quantity BIGINT,
    delivery_status VARCHAR(100),
    delivery_delay_days INTEGER
);

-- ============================================================
-- 3. FACT FOREIGN-KEY INDEXES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_ecom_customer
ON gold.fact_ecommerce_sales(customer_key);

CREATE INDEX IF NOT EXISTS idx_ecom_product
ON gold.fact_ecommerce_sales(product_key);

CREATE INDEX IF NOT EXISTS idx_ecom_date
ON gold.fact_ecommerce_sales(date_key);

CREATE INDEX IF NOT EXISTS idx_pos_product
ON gold.fact_pos_sales(product_key);

CREATE INDEX IF NOT EXISTS idx_pos_store
ON gold.fact_pos_sales(store_key);

CREATE INDEX IF NOT EXISTS idx_pos_date
ON gold.fact_pos_sales(date_key);

CREATE INDEX IF NOT EXISTS idx_returns_product
ON gold.fact_returns(product_key);

CREATE INDEX IF NOT EXISTS idx_inventory_product_store
ON gold.fact_inventory_snapshot(product_key, store_key);

CREATE INDEX IF NOT EXISTS idx_movements_date
ON gold.fact_inventory_movements(date_key);

CREATE INDEX IF NOT EXISTS idx_deliveries_supplier
ON gold.fact_supplier_deliveries(supplier_key);

